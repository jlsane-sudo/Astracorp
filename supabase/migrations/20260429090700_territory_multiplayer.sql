create or replace function public.rpc_build_territory_fort_secure(p_territory_id integer)
returns jsonb
as $fn$
declare
  v_save jsonb;
  v_territory jsonb;
  v_new_territory jsonb;
  v_territories jsonb;
  v_inventory jsonb;
  v_player_name text;
  v_fort numeric;
  v_tier int;
  v_mineral numeric;
  v_metal numeric;
  v_alloy numeric;
begin
  perform public._astracorp_check_cooldown('build_fort', p_territory_id, 120);

  v_save := public._astracorp_load_save_locked();
  v_player_name := coalesce(v_save #>> '{player,name}', 'Jugador');
  v_inventory := coalesce(v_save->'inventory', '{}'::jsonb);

  select territory into v_territory
  from jsonb_array_elements(coalesce(v_save->'territories', '[]'::jsonb)) territory
  where (territory->>'id')::int = p_territory_id
  limit 1;

  if v_territory is null then raise exception 'Territorio no valido.'; end if;
  if v_territory->>'controller' <> v_player_name then raise exception 'Solo puedes construir fortines en territorios bajo tu control.'; end if;

  v_fort := coalesce((v_territory->>'fortification')::numeric, 0);
  if v_fort >= 100 then raise exception 'Este territorio ya esta completamente fortificado.'; end if;

  v_tier := floor(v_fort / 25);
  v_mineral := 8 + v_tier * 4;
  v_metal := 3 + v_tier * 2;
  v_alloy := case when v_fort >= 50 then 1 + floor((v_fort - 50) / 25) else 0 end;

  if coalesce((v_inventory->>'mineral')::numeric, 0) < v_mineral
    or coalesce((v_inventory->>'metal_components')::numeric, 0) < v_metal
    or coalesce((v_inventory->>'alloy_frames')::numeric, 0) < v_alloy then
    raise exception 'Faltan recursos para el fortin.';
  end if;

  v_inventory := jsonb_set(v_inventory, '{mineral}', to_jsonb(coalesce((v_inventory->>'mineral')::numeric, 0) - v_mineral), true);
  v_inventory := jsonb_set(v_inventory, '{metal_components}', to_jsonb(coalesce((v_inventory->>'metal_components')::numeric, 0) - v_metal), true);
  v_inventory := jsonb_set(v_inventory, '{alloy_frames}', to_jsonb(coalesce((v_inventory->>'alloy_frames')::numeric, 0) - v_alloy), true);

  v_new_territory := jsonb_set(v_territory, '{fortification}', to_jsonb(public._astracorp_clamp(v_fort + 22, 0, 100)), true);
  v_new_territory := jsonb_set(v_new_territory, '{stability}', to_jsonb(public._astracorp_clamp(coalesce((v_territory->>'stability')::numeric, 0) + 10, 0, 100)), true);
  v_new_territory := jsonb_set(v_new_territory, '{threat}', to_jsonb(public._astracorp_clamp(coalesce((v_territory->>'threat')::numeric, 0) - 18, 0, 100)), true);
  v_new_territory := jsonb_set(v_new_territory, '{fortLevel}', to_jsonb(coalesce((v_territory->>'fortLevel')::int, 0) + 1), true);

  select jsonb_agg(case when (territory->>'id')::int = p_territory_id then v_new_territory else territory end order by ord)
  into v_territories
  from jsonb_array_elements(coalesce(v_save->'territories', '[]'::jsonb)) with ordinality items(territory, ord);

  v_save := jsonb_set(v_save, '{territories}', v_territories, true);
  v_save := jsonb_set(v_save, '{inventory}', v_inventory, true);

  perform public._astracorp_write_global_territory(p_territory_id, v_new_territory);

  insert into public.astracorp_territory_events(user_id, territory_id, action)
  values (auth.uid(), p_territory_id, 'build_fort');

  perform public._astracorp_store_save(v_save);
  return jsonb_build_object('ok', true, 'saveData', v_save, 'message', 'Fortin construido online.');
end;

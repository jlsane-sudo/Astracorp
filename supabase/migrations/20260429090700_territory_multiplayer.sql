create or replace function public.rpc_collect_occupation_taxes_secure(p_territory_id integer)
returns jsonb
as $fn$
declare
  v_save jsonb;
  v_player_name text;
  v_territory jsonb;
  v_company jsonb;
  v_companies jsonb := '[]'::jsonb;
  v_inventory jsonb;
  v_resource text;
  v_pending numeric;
  v_collected jsonb := '{}'::jsonb;
  v_collected_text text := '';
begin
  perform public._astracorp_check_cooldown('collect_tax', p_territory_id, 30);

  v_save := public._astracorp_load_save_locked();
  v_player_name := coalesce(v_save #>> '{player,name}', 'Jugador');
  v_inventory := coalesce(v_save->'inventory', '{}'::jsonb);

  select territory into v_territory
  from jsonb_array_elements(coalesce(v_save->'territories', '[]'::jsonb)) territory
  where (territory->>'id')::int = p_territory_id
  limit 1;

  if v_territory is null or v_territory->>'controller' <> v_player_name then
    raise exception 'Solo puedes cobrar tasas de territorios bajo tu control.';
  end if;

  for v_company in select value from jsonb_array_elements(coalesce(v_save->'companies', '[]'::jsonb)) loop
    v_pending := coalesce((v_company->>'occupationTaxPending')::numeric, 0);

    if coalesce((v_company->>'territoryId')::int, -1) = p_territory_id
      and coalesce(v_company->>'occupiedBy', '') = v_player_name
      and v_pending > 0 then
      v_resource := coalesce(nullif(v_company->>'occupationTaxResourceKey', ''), 'mineral');
      v_inventory := jsonb_set(v_inventory, array[v_resource], to_jsonb(coalesce((v_inventory->>v_resource)::numeric, 0) + v_pending), true);
      v_collected := jsonb_set(v_collected, array[v_resource], to_jsonb(coalesce((v_collected->>v_resource)::numeric, 0) + v_pending), true);
      v_company := jsonb_set(v_company, '{occupationTaxPending}', to_jsonb(0), true);
    end if;

    v_companies := v_companies || jsonb_build_array(v_company);
  end loop;

  if v_collected = '{}'::jsonb then
    raise exception 'No hay tasas pendientes en ese territorio.';
  end if;

  select string_agg(format('%s %s', value, key), ', ' order by key)
  into v_collected_text
  from jsonb_each_text(v_collected);

  v_save := jsonb_set(v_save, '{companies}', v_companies, true);
  v_save := jsonb_set(v_save, '{inventory}', v_inventory, true);

  insert into public.astracorp_territory_events(user_id, territory_id, action, payload)
  values (auth.uid(), p_territory_id, 'collect_tax', jsonb_build_object('collected', v_collected));

  perform public._astracorp_store_save(v_save);
  return jsonb_build_object('ok', true, 'saveData', v_save, 'collectedText', v_collected_text, 'message', 'Tasas cobradas online.');
end;

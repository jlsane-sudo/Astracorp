-- AstraCorp - territorios multijugador online
-- Version compatible con Supabase SQL Editor.

create table if not exists public.game_saves (
  user_id uuid primary key references auth.users(id) on delete cascade,
  save_data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.game_saves enable row level security;

drop policy if exists "Players can read own save" on public.game_saves;
create policy "Players can read own save"
  on public.game_saves for select
  using (auth.uid() = user_id);

drop policy if exists "Players can write own save" on public.game_saves;
create policy "Players can write own save"
  on public.game_saves for insert
  with check (auth.uid() = user_id);

drop policy if exists "Players can update own save" on public.game_saves;
create policy "Players can update own save"
  on public.game_saves for update
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create table if not exists public.astracorp_global_territories (
  territory_id integer primary key,
  state jsonb not null,
  controller text,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

alter table public.astracorp_global_territories enable row level security;

drop policy if exists "Players can read global territories" on public.astracorp_global_territories;
create policy "Players can read global territories"
  on public.astracorp_global_territories for select
  to authenticated
  using (true);

create table if not exists public.astracorp_territory_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  territory_id integer not null,
  action text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists astracorp_territory_events_user_action_idx
  on public.astracorp_territory_events(user_id, action, territory_id, created_at desc);

alter table public.astracorp_territory_events enable row level security;

drop policy if exists "Players can read own territory events" on public.astracorp_territory_events;
create policy "Players can read own territory events"
  on public.astracorp_territory_events for select
  using (auth.uid() = user_id);

create or replace function public._astracorp_clamp(p_value numeric, p_min numeric, p_max numeric)
returns numeric
as $fn$
  select least(p_max, greatest(p_min, coalesce(p_value, p_min)));
$fn$
language sql
immutable;

create or replace function public._astracorp_check_cooldown(p_action text, p_territory_id integer, p_seconds integer)
returns void
as $fn$
declare
  v_user uuid := auth.uid();
  v_last timestamptz;
  v_remaining integer;
begin
  if v_user is null then
    raise exception 'Debes iniciar sesion.';
  end if;

  select created_at into v_last
  from public.astracorp_territory_events
  where user_id = v_user
    and action = p_action
    and territory_id = p_territory_id
  order by created_at desc
  limit 1;

  if v_last is not null and v_last > now() - make_interval(secs => p_seconds) then
    v_remaining := greatest(1, ceil(extract(epoch from (v_last + make_interval(secs => p_seconds) - now())))::int);
    raise exception 'Accion en enfriamiento. Espera % segundos.', v_remaining;
  end if;
end;
$fn$
language plpgsql
security definer
set search_path = public;

create or replace function public._astracorp_seed_global_territories(p_user uuid, p_save jsonb)
returns void
as $fn$
begin
  insert into public.astracorp_global_territories(territory_id, state, controller, updated_by, updated_at)
  select (territory->>'id')::int, territory, nullif(territory->>'controller', ''), p_user, now()
  from jsonb_array_elements(coalesce(p_save->'territories', '[]'::jsonb)) territory
  where territory ? 'id'
  on conflict (territory_id) do nothing;
end;
$fn$
language plpgsql
security definer
set search_path = public;

create or replace function public._astracorp_apply_global_territories(p_save jsonb)
returns jsonb
as $fn$
declare
  v_territories jsonb;
begin
  select jsonb_agg(coalesce(global_state.state, local_state.territory) order by local_state.ord)
  into v_territories
  from jsonb_array_elements(coalesce(p_save->'territories', '[]'::jsonb)) with ordinality local_state(territory, ord)
  left join public.astracorp_global_territories global_state
    on global_state.territory_id = (local_state.territory->>'id')::int;

  if v_territories is null then
    return p_save;
  end if;

  return jsonb_set(p_save, '{territories}', v_territories, true);
end;
$fn$
language plpgsql
security definer
set search_path = public;

create or replace function public._astracorp_load_save_locked()
returns jsonb
as $fn$
declare
  v_user uuid := auth.uid();
  v_save jsonb;
begin
  if v_user is null then
    raise exception 'Debes iniciar sesion.';
  end if;

  select save_data into v_save
  from public.game_saves
  where user_id = v_user
  for update;

  if v_save is null then
    raise exception 'No hay partida guardada en esta cuenta.';
  end if;

  perform public._astracorp_seed_global_territories(v_user, v_save);
  return public._astracorp_apply_global_territories(v_save);
end;
$fn$
language plpgsql
security definer
set search_path = public;

create or replace function public._astracorp_store_save(p_save jsonb)
returns void
as $fn$
begin
  update public.game_saves
  set save_data = p_save,
      updated_at = now()
  where user_id = auth.uid();
end;
$fn$
language plpgsql
security definer
set search_path = public;

create or replace function public._astracorp_write_global_territory(p_territory_id integer, p_state jsonb)
returns void
as $fn$
begin
  insert into public.astracorp_global_territories(territory_id, state, controller, updated_by, updated_at)
  values (p_territory_id, p_state, nullif(p_state->>'controller', ''), auth.uid(), now())
  on conflict (territory_id) do update set
    state = excluded.state,
    controller = excluded.controller,
    updated_by = excluded.updated_by,
    updated_at = now();
end;
$fn$
language plpgsql
security definer
set search_path = public;

create or replace function public._astracorp_set_player_values(p_save jsonb, p_credits numeric, p_energy numeric, p_health numeric default null)
returns jsonb
as $fn$
declare
  v_player jsonb := coalesce(p_save->'player', '{}'::jsonb);
begin
  v_player := jsonb_set(v_player, '{credits}', to_jsonb(round(greatest(0, p_credits)::numeric, 2)), true);
  v_player := jsonb_set(v_player, '{energy}', to_jsonb(greatest(0, floor(p_energy))::int), true);

  if p_health is not null then
    v_player := jsonb_set(v_player, '{health}', to_jsonb(public._astracorp_clamp(p_health, 0, 100)), true);
  end if;

  return jsonb_set(p_save, '{player}', v_player, true);
end;
$fn$
language plpgsql
immutable;


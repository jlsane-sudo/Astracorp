create or replace function public.rpc_attack_territory_secure(p_territory_id integer)
returns jsonb
as $fn$
declare
  v_save jsonb;
  v_territory jsonb;
  v_new_territory jsonb;
  v_territories jsonb;
  v_campaign jsonb;
  v_next_campaign jsonb;
  v_memory jsonb;
  v_player_name text;
  v_credits numeric;
  v_energy numeric;
  v_health numeric;
  v_level numeric;
  v_inventory jsonb;
  v_controlled numeric;
  v_attack_power numeric;
  v_defense_power numeric;
  v_current_progress numeric;
  v_progress_gain numeric;
  v_next_progress numeric;
  v_chance numeric;
  v_win boolean;
  v_completed boolean := false;
  v_reward numeric := 0;
  v_stats jsonb;
begin
  perform public._astracorp_check_cooldown('attack', p_territory_id, 45);

  v_save := public._astracorp_load_save_locked();
  v_player_name := coalesce(v_save #>> '{player,name}', 'Jugador');
  v_credits := coalesce((v_save #>> '{player,credits}')::numeric, 0);
  v_energy := coalesce((v_save #>> '{player,energy}')::numeric, 0);
  v_health := coalesce((v_save #>> '{player,health}')::numeric, 100);
  v_level := coalesce((v_save #>> '{player,level}')::numeric, 1);
  v_inventory := coalesce(v_save->'inventory', '{}'::jsonb);

  select territory into v_territory
  from jsonb_array_elements(coalesce(v_save->'territories', '[]'::jsonb)) territory
  where (territory->>'id')::int = p_territory_id
  limit 1;

  if v_territory is null then raise exception 'Territorio no valido.'; end if;
  if v_territory->>'controller' = v_player_name then raise exception 'Ya controlas este territorio.'; end if;
  if v_energy < 32 then raise exception 'Necesitas 32 de energia.'; end if;
  if v_credits < 4 then raise exception 'Necesitas 4 creditos.'; end if;
  if v_health < 15 then raise exception 'Integridad critica: repara en la sede antes de conquistar.'; end if;

  select count(*) into v_controlled
  from jsonb_array_elements(coalesce(v_save->'territories', '[]'::jsonb)) territory
  where territory->>'controller' = v_player_name;

  v_campaign := case
    when v_territory ? 'campaign' and coalesce(v_territory->'campaign'->>'ownerName', '') = v_player_name
      then v_territory->'campaign'
    else null
  end;
  v_current_progress := public._astracorp_clamp(coalesce((v_campaign->>'progress')::numeric, 0), 0, 100);
  v_attack_power :=
    8
    + v_level * 2.1
    + v_controlled * 0.7
    + sqrt(greatest(0, coalesce((v_inventory->>'mineral')::numeric, 0)));
  v_defense_power := greatest(
    8,
    case when coalesce(v_territory->>'controller', '') <> '' then 24 else 15 end
      + coalesce((v_territory->>'stability')::numeric, 0) * 0.26
      + coalesce((v_territory->>'fortification')::numeric, 0) * 0.34
      - coalesce((v_territory->>'threat')::numeric, 0) * 0.05
  );
  v_chance := public._astracorp_clamp(
    42 + (v_attack_power - v_defense_power) * 3.4 + v_current_progress * 0.1,
    case when coalesce(v_territory->>'controller', '') <> '' then 8 else 16 end,
    case when coalesce(v_territory->>'controller', '') <> '' then 62 else 76 end
  );
  v_win := random() * 100 < v_chance;
  v_progress_gain := case
    when v_win and coalesce(v_territory->>'controller', '') <> '' then 26
    when v_win then 38
    when coalesce(v_territory->>'controller', '') <> '' then 6
    else 10
  end;
  v_next_progress := public._astracorp_clamp(v_current_progress + v_progress_gain, 0, 100);
  v_completed := v_win and v_next_progress >= 100;

  if v_completed then
    v_reward := round((greatest(4, v_defense_power / 4.2 + coalesce((v_territory->>'threat')::numeric, 0) * 0.06) * (0.9 + random() * 0.3))::numeric, 2);
    v_memory := coalesce(v_territory->'sectorMemory', '{}'::jsonb)
      || jsonb_build_object(
        'firstControlledAt', coalesce(v_territory #> '{sectorMemory,firstControlledAt}', to_jsonb(floor(extract(epoch from clock_timestamp()) * 1000)::numeric)),
        'firstControlledDay', coalesce(v_territory #> '{sectorMemory,firstControlledDay}', to_jsonb(coalesce((v_save->>'day')::int, 1))),
        'lastConqueredAt', floor(extract(epoch from clock_timestamp()) * 1000)::numeric,
        'lastConqueredDay', coalesce((v_save->>'day')::int, 1),
        'conqueredCount', coalesce((v_territory #>> '{sectorMemory,conqueredCount}')::int, 0) + 1,
        'lastEvent', 'Conquistado por ' || v_player_name
      );
    v_new_territory := jsonb_set(v_territory, '{controller}', to_jsonb(v_player_name), true);
    v_new_territory := jsonb_set(v_new_territory, '{stability}', to_jsonb(58), true);
    v_new_territory := jsonb_set(v_new_territory, '{threat}', to_jsonb(38), true);
    v_new_territory := jsonb_set(v_new_territory, '{fortification}', to_jsonb(greatest(6, coalesce((v_territory->>'fortification')::numeric, 0))), true);
    v_new_territory := jsonb_set(v_new_territory, '{campaign}', 'null'::jsonb, true);
    v_new_territory := jsonb_set(v_new_territory, '{enemyCampaign}', 'null'::jsonb, true);
    v_new_territory := jsonb_set(v_new_territory, '{siegeTick}', to_jsonb(0), true);
    v_new_territory := jsonb_set(v_new_territory, '{siegeAttacker}', 'null'::jsonb, true);
    v_new_territory := jsonb_set(v_new_territory, '{siegeStartedAt}', 'null'::jsonb, true);
    v_new_territory := jsonb_set(v_new_territory, '{sectorMemory}', v_memory, true);
  else
    v_next_campaign := jsonb_build_object(
      'ownerName', v_player_name,
      'progress', v_next_progress,
      'stageId', case
        when v_next_progress >= 76 then 'consolidation'
        when v_next_progress >= 51 then 'assault'
        when v_next_progress >= 26 then 'sabotage'
        else 'recon'
      end,
      'attempts', coalesce((v_campaign->>'attempts')::int, 0) + 1,
      'targetController', nullif(v_territory->>'controller', ''),
      'updatedAt', floor(extract(epoch from clock_timestamp()) * 1000)::numeric
    );
    v_new_territory := jsonb_set(v_territory, '{campaign}', v_next_campaign, true);
    v_new_territory := jsonb_set(
      v_new_territory,
      '{stability}',
      to_jsonb(public._astracorp_clamp(coalesce((v_territory->>'stability')::numeric, 0) - case when v_win then 4 else 1 end, 0, 100)),
      true
    );
    v_new_territory := jsonb_set(
      v_new_territory,
      '{threat}',
      to_jsonb(public._astracorp_clamp(coalesce((v_territory->>'threat')::numeric, 0) + case when v_win then 5 else 2 end, 0, 100)),
      true
    );
  end if;

  select jsonb_agg(case when (territory->>'id')::int = p_territory_id then v_new_territory else territory end order by ord)
  into v_territories
  from jsonb_array_elements(coalesce(v_save->'territories', '[]'::jsonb)) with ordinality items(territory, ord);

  v_save := jsonb_set(v_save, '{territories}', v_territories, true);
  v_save := public._astracorp_set_player_values(v_save, v_credits - 4 + v_reward, v_energy - 32, case when v_win then v_health - 7 else v_health - 24 end);

  v_stats := coalesce(v_save->'stats', '{}'::jsonb);
  v_stats := jsonb_set(v_stats, '{battles}', to_jsonb(coalesce((v_stats->>'battles')::int, 0) + 1), true);
  v_stats := jsonb_set(v_stats, '{conquests}', to_jsonb(coalesce((v_stats->>'conquests')::int, 0) + case when v_completed then 1 else 0 end), true);
  v_save := jsonb_set(v_save, '{stats}', v_stats, true);

  perform public._astracorp_write_global_territory(p_territory_id, v_new_territory);

  insert into public.astracorp_territory_events(user_id, territory_id, action, payload)
  values (auth.uid(), p_territory_id, 'attack', jsonb_build_object(
    'win', v_win,
    'completed', v_completed,
    'rewardCredits', v_reward,
    'chance', v_chance,
    'progress', v_next_progress
  ));

  perform public._astracorp_store_save(v_save);

  return jsonb_build_object(
    'ok', true,
    'saveData', v_save,
    'result', jsonb_build_object(
      'win', v_win,
      'completed', v_completed,
      'rewardCredits', v_reward,
      'chance', v_chance,
      'progress', v_next_progress
    )
  );
end;
$fn$
language plpgsql
security definer
set search_path = public;


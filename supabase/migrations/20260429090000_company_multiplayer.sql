create or replace function public._astracorp_company_build_cost(p_type text, p_owned integer)
returns numeric
as $fn$
declare
  v_meta jsonb := public._astracorp_company_meta(p_type);
  v_base numeric;
begin
  if v_meta is null then return 0; end if;
  v_base := coalesce((v_meta->>'buildCost')::numeric, 0);
  return greatest(v_base, round((v_base * power(1.18, greatest(0, coalesce(p_owned, 0))))::numeric, 0));
end;
$fn$
language plpgsql
immutable;

create or replace function public._astracorp_company_load_save_locked()
returns jsonb
as $fn$
declare
  v_user uuid := auth.uid();
  v_save jsonb;
begin
  if v_user is null then
    raise exception 'Debes iniciar sesion.';
  end if;

  v_save := (
    select save_data
    from public.game_saves
    where user_id = v_user
    for update
  );

  if v_save is null then
    raise exception 'No hay partida guardada en esta cuenta.';
  end if;

  return v_save;
end;
$fn$
language plpgsql
security definer
set search_path = public;

create or replace function public._astracorp_company_store_save(p_save jsonb)
returns void
as $fn$
begin
  update public.game_saves
  set save_data = p_save,
      updated_at = now()
  where user_id = auth.uid();
end;

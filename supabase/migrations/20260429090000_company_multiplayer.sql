create or replace function public._astracorp_collect_companies(p_company_id text default null, p_company_type_key text default null, p_region_key text default null, p_spend_energy numeric default 1)
returns jsonb
as $fn$
declare
  v_save jsonb;
  v_companies jsonb := '[]'::jsonb;
  v_inventory jsonb;
  v_company jsonb;
  v_meta jsonb;
  v_type text;
  v_resource_key text;
  v_resource_label text;
  v_storage numeric;
  v_total numeric := 0;
  v_totals jsonb := '{}'::jsonb;
  v_match boolean;
  v_summary text;
begin
  v_save := public._astracorp_company_load_save_locked();
  v_save := public._astracorp_company_hydrate(v_save);
  if p_spend_energy > 0 then
    v_save := public._astracorp_company_spend_energy(v_save, p_spend_energy);
  end if;
  v_inventory := coalesce(v_save->'inventory', '{}'::jsonb);

  for v_company in select value from jsonb_array_elements(coalesce(v_save->'companies', '[]'::jsonb)) loop
    v_type := coalesce(v_company->>'companyType', v_company->>'type');
    v_meta := public._astracorp_company_meta(v_type);
    v_storage := coalesce((v_company->>'storage')::numeric, 0);
    v_match := true;
    if p_company_id is not null then v_match := v_company->>'id' = p_company_id; end if;
    if p_company_type_key is not null then v_match := v_match and v_type = p_company_type_key; end if;
    if p_region_key is not null then v_match := v_match and coalesce(v_company->>'regionKey', 'alpha-district') = p_region_key; end if;

    if v_match and v_meta is not null and v_storage > 0 and coalesce((v_meta->>'ratePerHour')::numeric, 0) > 0 then
      v_resource_key := v_meta->>'resourceKey';
      v_resource_label := v_meta->>'resourceLabel';
      v_inventory := jsonb_set(v_inventory, array[v_resource_key], to_jsonb(round((coalesce((v_inventory->>v_resource_key)::numeric, 0) + v_storage)::numeric, 2)), true);
      v_totals := jsonb_set(v_totals, array[v_resource_key], to_jsonb(round((coalesce((v_totals->>v_resource_key)::numeric, 0) + v_storage)::numeric, 2)), true);
      v_total := round((v_total + v_storage)::numeric, 2);
      v_company := jsonb_set(v_company, '{storage}', to_jsonb(0), true);
      v_company := jsonb_set(v_company, '{lastCollectedAt}', to_jsonb(floor(extract(epoch from clock_timestamp()) * 1000)::bigint), true);
      v_company := jsonb_set(v_company, '{lastTickAt}', to_jsonb(floor(extract(epoch from clock_timestamp()) * 1000)::bigint), true);
    end if;

    v_companies := v_companies || jsonb_build_array(v_company);
  end loop;

  if v_total <= 0 then
    raise exception 'No hay produccion acumulada.';
  end if;

  v_summary := (
    select string_agg(format('%s %s', value, key), ', ' order by key)
    from jsonb_each_text(v_totals)
  );

  v_save := jsonb_set(v_save, '{inventory}', v_inventory, true);
  v_save := jsonb_set(v_save, '{companies}', v_companies, true);

  insert into public.astracorp_company_events(user_id, action, company_id, company_type, resource_key, amount)
  values (auth.uid(), case when p_company_id is not null then 'collect_one' when p_company_type_key is not null then 'collect_group' else 'collect_all_ad' end, p_company_id, p_company_type_key, null, v_total);

  perform public._astracorp_company_store_save(v_save);
  return jsonb_build_object('ok', true, 'saveData', v_save, 'amount', v_total, 'resourceLabel', coalesce(v_resource_label, ''), 'totals', v_totals, 'summary', coalesce(v_summary, 'Produccion recogida'));
end;

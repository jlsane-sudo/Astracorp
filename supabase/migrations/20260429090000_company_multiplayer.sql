create table if not exists public.game_saves (
  user_id uuid primary key references auth.users(id) on delete cascade,
  save_data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.game_saves enable row level security;

drop policy if exists "Players can read own save" on public.game_saves;
create policy "Players can read own save"
  on public.game_saves for select
  using (auth.uid() = user_id);

drop policy if exists "Players can write own save" on public.game_saves;
create policy "Players can write own save"
  on public.game_saves for insert
  with check (auth.uid() = user_id);

drop policy if exists "Players can update own save" on public.game_saves;
create policy "Players can update own save"
  on public.game_saves for update
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create table if not exists public.astracorp_company_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  company_id text,
  company_type text,
  resource_key text,
  amount numeric not null default 0,
  credits numeric not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists astracorp_company_events_user_idx
  on public.astracorp_company_events(user_id, created_at desc);

alter table public.astracorp_company_events enable row level security;

drop policy if exists "Players can read own company events" on public.astracorp_company_events;
create policy "Players can read own company events"
  on public.astracorp_company_events for select
  using (auth.uid() = user_id);


create or replace function public._astracorp_company_spend_energy(p_save jsonb, p_amount numeric)
returns jsonb
as $fn$
declare
  v_energy numeric := coalesce((p_save #>> '{player,energy}')::numeric, 0);
begin
  if v_energy < p_amount then
    raise exception 'Necesitas % de energia.', p_amount;
  end if;

  return jsonb_set(p_save, '{player,energy}', to_jsonb(greatest(0, floor(v_energy - p_amount))::int), true);
end;
$fn$
language plpgsql
immutable;

create or replace function public._astracorp_company_hydrate(p_save jsonb)
returns jsonb
as $fn$
declare
  v_now_ms numeric := extract(epoch from clock_timestamp()) * 1000;
  v_inventory jsonb := coalesce(p_save->'inventory', '{}'::jsonb);
  v_companies jsonb := '[]'::jsonb;
  v_company jsonb;
  v_meta jsonb;
  v_type text;
  v_rate numeric;
  v_max numeric;
  v_storage numeric;
  v_last numeric;
  v_elapsed_hours numeric;
  v_produced numeric;
  v_input jsonb;
  v_input_key text;
  v_input_amount numeric;
  v_max_by_inputs numeric;
  v_available numeric;
begin
  for v_company in select value from jsonb_array_elements(coalesce(p_save->'companies', '[]'::jsonb)) loop
    if coalesce((v_company->>'active')::boolean, true) = false then
      v_companies := v_companies || jsonb_build_array(v_company);
      continue;
    end if;

    v_type := coalesce(v_company->>'companyType', v_company->>'type');
    v_meta := public._astracorp_company_meta(v_type);
    if v_meta is null then
      v_companies := v_companies || jsonb_build_array(v_company);
      continue;
    end if;

    v_rate := coalesce((v_company->>'effectiveRatePerHour')::numeric, (v_meta->>'ratePerHour')::numeric, 0);
    v_max := coalesce((v_company->>'maxStorage')::numeric, (v_meta->>'maxStorage')::numeric, 0);
    v_storage := least(v_max, greatest(0, coalesce((v_company->>'storage')::numeric, 0)));
    v_last := coalesce((v_company->>'lastTickAt')::numeric, (v_company->>'lastCollectedAt')::numeric, (v_company->>'createdAt')::numeric, v_now_ms);
    v_elapsed_hours := greatest(0, v_now_ms - v_last) / 3600000.0;
    v_produced := least(greatest(0, v_max - v_storage), greatest(0, v_elapsed_hours * v_rate));

    if jsonb_array_length(coalesce(v_meta->'inputs', '[]'::jsonb)) > 0 and v_produced > 0 then
      v_max_by_inputs := v_produced;
      for v_input in select value from jsonb_array_elements(v_meta->'inputs') loop
        v_input_key := v_input->>'key';
        v_input_amount := coalesce((v_input->>'amount')::numeric, 0);
        if v_input_amount > 0 then
          v_available := coalesce((v_inventory->>v_input_key)::numeric, 0);
          v_max_by_inputs := least(v_max_by_inputs, v_available / v_input_amount);
        end if;
      end loop;
      v_produced := greatest(0, v_max_by_inputs);

      if v_produced > 0 then
        for v_input in select value from jsonb_array_elements(v_meta->'inputs') loop
          v_input_key := v_input->>'key';
          v_input_amount := coalesce((v_input->>'amount')::numeric, 0);
          if v_input_amount > 0 then
            v_inventory := jsonb_set(v_inventory, array[v_input_key], to_jsonb(round(greatest(0, coalesce((v_inventory->>v_input_key)::numeric, 0) - v_input_amount * v_produced)::numeric, 2)), true);
          end if;
        end loop;
      end if;
    end if;

    v_company := jsonb_set(v_company, '{storage}', to_jsonb(round(least(v_max, v_storage + v_produced)::numeric, 2)), true);
    v_company := jsonb_set(v_company, '{lastTickAt}', to_jsonb(floor(v_now_ms)::bigint), true);
    v_company := jsonb_set(v_company, '{companyType}', to_jsonb(v_type), true);
    v_company := jsonb_set(v_company, '{type}', to_jsonb(v_type), true);
    v_company := jsonb_set(v_company, '{name}', to_jsonb(coalesce(v_company->>'name', v_meta->>'name')), true);
    v_company := jsonb_set(v_company, '{maxStorage}', to_jsonb(v_max), true);

    v_companies := v_companies || jsonb_build_array(v_company);
  end loop;

  p_save := jsonb_set(p_save, '{inventory}', v_inventory, true);
  p_save := jsonb_set(p_save, '{companies}', v_companies, true);
  return p_save;
end;
$fn$
language plpgsql
security definer
set search_path = public;

create or replace function public.rpc_build_company_secure(p_company_type_key text, p_region_key text default null, p_territory_id integer default null)
returns jsonb
as $fn$
declare
  v_save jsonb;
  v_meta jsonb;
  v_type text := p_company_type_key;
  v_owned integer;
  v_cost numeric;
  v_credits numeric;
  v_level numeric;
  v_now_ms bigint := floor(extract(epoch from clock_timestamp()) * 1000)::bigint;
  v_company jsonb;
  v_stats jsonb;
begin
  v_meta := public._astracorp_company_meta(v_type);
  if v_meta is null then raise exception 'Tipo de empresa no valido.'; end if;

  v_save := public._astracorp_company_load_save_locked();
  v_save := public._astracorp_company_hydrate(v_save);
  v_level := coalesce((v_save #>> '{player,level}')::numeric, 1);
  if v_level < coalesce((v_meta->>'unlockLevel')::numeric, 1) then
    raise exception 'Necesitas nivel % para construir esta empresa.', v_meta->>'unlockLevel';
  end if;

  v_owned := (
    select count(*)::int
    from jsonb_array_elements(coalesce(v_save->'companies', '[]'::jsonb)) c
    where coalesce(c->>'companyType', c->>'type') = v_type
  );
  v_cost := public._astracorp_company_build_cost(v_type, v_owned);
  v_credits := coalesce((v_save #>> '{player,credits}')::numeric, 0);
  if v_credits < v_cost then raise exception 'Creditos insuficientes.'; end if;

  v_save := public._astracorp_company_spend_energy(v_save, 4);
  v_save := jsonb_set(v_save, '{player,credits}', to_jsonb(round((v_credits - v_cost)::numeric, 2)), true);

  v_company := jsonb_build_object(
    'id', v_now_ms::text || '-' || substr(md5(random()::text), 1, 8),
    'companyType', v_type,
    'type', v_type,
    'name', v_meta->>'name',
    'storage', 0,
    'maxStorage', coalesce((v_meta->>'maxStorage')::numeric, 0),
    'regionKey', coalesce(p_region_key, v_save #>> '{player,currentRegion}', 'alpha-district'),
    'territoryId', p_territory_id,
    'active', true,
    'status', 'active',
    'occupiedBy', null,
    'occupationTaxPending', 0,
    'occupationTaxResourceKey', v_meta->>'resourceKey',
    'ownerName', coalesce(v_save #>> '{player,name}', 'Jugador'),
    'createdAt', v_now_ms,
    'lastCollectedAt', v_now_ms,
    'lastTickAt', v_now_ms
  );

  v_save := jsonb_set(v_save, '{companies}', coalesce(v_save->'companies', '[]'::jsonb) || jsonb_build_array(v_company), true);
  v_stats := coalesce(v_save->'stats', '{}'::jsonb);
  v_stats := jsonb_set(v_stats, '{companiesBuilt}', to_jsonb(coalesce((v_stats->>'companiesBuilt')::int, 0) + 1), true);
  v_save := jsonb_set(v_save, '{stats}', v_stats, true);

  insert into public.astracorp_company_events(user_id, action, company_id, company_type, credits)
  values (auth.uid(), 'build', v_company->>'id', v_type, v_cost);

  perform public._astracorp_company_store_save(v_save);
  return jsonb_build_object('ok', true, 'saveData', v_save, 'company', v_company, 'cost', v_cost);
end;
$fn$
language plpgsql
security definer
set search_path = public;

create or replace function public.rpc_sell_company_secure(p_company_id text)
returns jsonb
as $fn$
declare
  v_save jsonb;
  v_company jsonb;
  v_companies jsonb := '[]'::jsonb;
  v_type text;
  v_owned integer;
  v_refund numeric;
  v_credits numeric;
begin
  if p_company_id is null then raise exception 'Empresa no valida.'; end if;

  v_save := public._astracorp_company_load_save_locked();
  v_save := public._astracorp_company_hydrate(v_save);

  v_company := (
    select value
    from jsonb_array_elements(coalesce(v_save->'companies', '[]'::jsonb))
    where value->>'id' = p_company_id
    limit 1
  );

  if v_company is null then raise exception 'La empresa ya no existe.'; end if;
  v_type := coalesce(v_company->>'companyType', v_company->>'type');
  if public._astracorp_company_meta(v_type) is null then raise exception 'Tipo de empresa no valido.'; end if;

  v_owned := (
    select count(*)::int
    from jsonb_array_elements(coalesce(v_save->'companies', '[]'::jsonb)) c
    where coalesce(c->>'companyType', c->>'type') = v_type
  );
  v_refund := round(greatest(1, public._astracorp_company_build_cost(v_type, greatest(0, v_owned - 1)) * 0.45)::numeric, 2);

  v_companies := (
    select coalesce(jsonb_agg(value), '[]'::jsonb)
    from jsonb_array_elements(coalesce(v_save->'companies', '[]'::jsonb))
    where value->>'id' <> p_company_id
  );

  v_credits := coalesce((v_save #>> '{player,credits}')::numeric, 0);
  v_save := jsonb_set(v_save, '{companies}', v_companies, true);
  v_save := jsonb_set(v_save, '{player,credits}', to_jsonb(round((v_credits + v_refund)::numeric, 2)), true);

  insert into public.astracorp_company_events(user_id, action, company_id, company_type, credits)
  values (auth.uid(), 'sell', p_company_id, v_type, v_refund);

  perform public._astracorp_company_store_save(v_save);
  return jsonb_build_object('ok', true, 'saveData', v_save, 'refund', v_refund);
end;
